"""Build the chibi hero rig and export it for Godot. Run headless:

    blender --background --python tools/blender/build_rig.py

Writes two files and nothing else:

    assets/characters/hero_chibi.glb
    assets/characters/hero_chibi.provenance.json

The manifest is not decoration. GDD 17 lists "Source-game asset/legal
dependency" as the risk with the highest impact on this project, and the
mitigation it names is "documented provenance". A manifest nobody checks is
provenance as a comment, and the tests in `tests/test_provenance.gd` are what
turn it into a gate. This file therefore writes the hash it just produced, and
the test re-hashes the committed bytes; a manifest whose hash no longer matches
its asset is a failure, not a stale comment.

The `.blend` is deliberately not committed. The rig is a function of
`shinobi_rig.py`, so committing the binary would create two sources of truth
for the same character, and the one that is hard to diff is the one that
would drift.
"""

from __future__ import annotations

import hashlib
import json
import os
import sys

import bpy

sys.path.insert(0, os.path.dirname(os.path.abspath(__file__)))

import shinobi_rig as rig  # noqa: E402

REPO_ROOT = os.path.abspath(os.path.join(os.path.dirname(__file__), "..", ".."))
ASSET_DIR = os.path.join(REPO_ROOT, "assets", "characters")
ASSET_NAME = "hero_chibi"

MANIFEST_SCHEMA = "shinobi.asset-provenance/1"


def export_glb(path: str) -> None:
    """glTF binary, +Y up, metres, with the rig kept as a real skeleton.

    The two export flags that are load-bearing:

    - `export_yup=True` is the glTF convention and the one Godot expects. If
      this is ever flipped, the character arrives lying down and nothing errors
      -- it just looks wrong -- which is why the proportions test re-imports the
      glTF and measures it rather than trusting this call.
    - `export_animations` stays on even though there are no clips yet. GDD
      13.3's AnimationBridge wants "imported skeletons ... and original attack
      clips", and Decision 4 in Docs/ARCHITECTURE.md records that sweeps may now
      bake from clips once one exists. Building the export without animations
      would mean re-plumbing the pipeline at exactly the moment the rig starts
      being the thing it is for.
    """
    bpy.ops.export_scene.gltf(
        filepath=path,
        export_format="GLB",
        export_yup=True,
        export_skins=True,
        export_animations=True,
        export_apply=False,
    )


def write_manifest(path: str, glb_path: str) -> dict:
    """Write the sidecar provenance record for an exported asset."""
    with open(glb_path, "rb") as handle:
        data = handle.read()

    manifest = {
        "schema": MANIFEST_SCHEMA,
        "asset": os.path.basename(glb_path),
        "kind": "model",
        "provenance": "ORIGINAL",
        "origin": (
            "Generated by tools/blender/shinobi_rig.py from parametric box "
            "primitives. No mesh was traced, sculpted from a reference image, "
            "retargeted from another production, or downloaded."
        ),
        "author": "SHINOBI: Blade & Loop",
        "license": "CC0-1.0",
        "generated_by": f"Blender {bpy.app.version_string}",
        "generator": "tools/blender/build_rig.py",
        "sources": [],
        "gdd": ["11.2", "13.3"],
        "bytes": len(data),
        "sha256": hashlib.sha256(data).hexdigest(),
    }

    os.makedirs(os.path.dirname(path), exist_ok=True)
    with open(path, "w", encoding="utf-8", newline="\n") as handle:
        json.dump(manifest, handle, indent=2, sort_keys=True)
        handle.write("\n")
    return manifest


def main() -> None:
    collection, arm_obj, p = rig.build_hero(ASSET_NAME)
    rig._triangulate(collection)
    measurements = rig.measure(collection, ASSET_NAME)

    glb_path = os.path.join(ASSET_DIR, f"{ASSET_NAME}.glb")
    manifest_path = os.path.join(ASSET_DIR, f"{ASSET_NAME}.provenance.json")

    os.makedirs(ASSET_DIR, exist_ok=True)
    export_glb(glb_path)
    manifest = write_manifest(manifest_path, glb_path)

    print(f"RIG_HEADS_TALL={measurements['heads_tall']:.4f}")
    print(f"RIG_TOTAL_HEIGHT={measurements['total_height']:.4f}")
    print(f"RIG_TRI_COUNT={measurements['tri_count']}")
    print(f"RIG_GLTF={os.path.relpath(glb_path, REPO_ROOT)}")
    print(f"RIG_BYTES={manifest['bytes']}")
    print(f"RIG_SHA256={manifest['sha256']}")


if __name__ == "__main__":
    main()